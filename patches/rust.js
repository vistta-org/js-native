import fs from "@vistta/fs";
import { initCall, PLUGINS } from "../plugins.config.js";
import { getInfo, writeIfChanged } from "../utils/index.js";

const SHARED = { begin: "# vistta:plugins:begin", end: "# vistta:plugins:end" };
const MOBILE = { begin: "# vistta:plugins-mobile:begin", end: "# vistta:plugins-mobile:end" };
const DESKTOP = { begin: "# vistta:plugins-desktop:begin", end: "# vistta:plugins-desktop:end" };

export async function patchMainRs(targetDir, config) {
  const mainPath = fs.resolve(targetDir, "src", "main.rs");
  await fs.mkdir(fs.resolve(targetDir, "src"), { recursive: true });
  const { lib } = await getInfo(config);
  const appId = config?.app?.id || "org.vistta.app";
  const content = `// Generated by @vistta/js-runtime. Do not edit by hand.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

fn main() {
    #[cfg(target_os = "windows")]
    set_app_user_model_id();
    ${lib}::run();
}

#[cfg(target_os = "windows")]
fn set_app_user_model_id() {
    use std::os::windows::ffi::OsStrExt;
    use std::ffi::OsStr;
    let wide: Vec<u16> = OsStr::new(${JSON.stringify(appId)})
        .encode_wide()
        .chain(std::iter::once(0))
        .collect();
    unsafe {
        let _ = windows::Win32::UI::Shell::SetCurrentProcessExplicitAppUserModelID(
            windows::core::PCWSTR(wide.as_ptr())
        );
    }
}
`;
  await writeIfChanged(mainPath, content);
}

/**
 * Generates src/lib.rs from the plugin SoT.
 * Always regenerated; never patched in place.
 */
export async function patchLibRs(targetDir, config) {
  const libPath = fs.resolve(targetDir, "src", "lib.rs");
  await fs.mkdir(fs.resolve(targetDir, "src"), { recursive: true });

  const sharedPlugins = PLUGINS.filter((p) => !p.platforms);
  const desktopOnly = PLUGINS.filter((p) => p.platforms && p.platforms.includes("desktop") && !sharedPlugins.includes(p));
  const mobileOnly = PLUGINS.filter(
    (p) => p.platforms && (p.platforms.includes("android") || p.platforms.includes("ios")) && !sharedPlugins.includes(p),
  );

  const indent = (s, n) => s.replace(/^/gm, " ".repeat(n));
  const sharedChain = sharedPlugins.map((p) => `.plugin(${initCall(p)})`).join("\n");
  const desktopChain = desktopOnly.map((p) => `.plugin(${initCall(p)})`).join("\n");
  const mobileChain = mobileOnly.map((p) => `.plugin(${initCall(p)})`).join("\n");

  const background = !!config?.app?.background;

  let desktopBlock = "";
  if (background) {
    desktopBlock = `
    #[cfg(not(any(target_os = "android", target_os = "ios")))]
    let builder = builder${desktopChain ? "\n" + indent(desktopChain, 8) : ""}
        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                let _ = window.hide();
                api.prevent_close();
            }
        })
        .setup(|app| {
            use tauri::tray::TrayIconBuilder;
            use tauri::menu::{Menu, MenuItem};

            let quit_i = MenuItem::with_id(app, "quit", "Quit", true, None::<&str>)?;
            let show_i = MenuItem::with_id(app, "show", "Show", true, None::<&str>)?;
            let menu = Menu::with_items(app, &[&show_i, &quit_i])?;

            let _tray = TrayIconBuilder::new()
                .icon(app.default_window_icon().unwrap().clone())
                .menu(&menu)
                .on_menu_event(|app, event| match event.id.as_ref() {
                    "quit" => { app.exit(0); }
                    "show" => {
                        if let Some(window) = app.get_webview_window("main") {
                            let _ = window.show();
                            let _ = window.set_focus();
                        }
                    }
                    _ => {}
                })
                .build(app)?;

            Ok(())
        });
`;
  } else if (desktopChain) {
    desktopBlock = `
    #[cfg(not(any(target_os = "android", target_os = "ios")))]
    let builder = builder
${indent(desktopChain, 8)};
`;
  }

  const mobileBlock = mobileChain
    ? `
    #[cfg(any(target_os = "android", target_os = "ios"))]
    let builder = builder
${indent(mobileChain, 8)};
`
    : "";

  const managerUse = background
    ? '    #[cfg(not(any(target_os = "android", target_os = "ios")))]\n    use tauri::Manager;\n'
    : "";

  const content = `// Generated by @vistta/js-runtime. Do not edit by hand.
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
${managerUse}    env_logger::init();
    log::info!("Starting Vistta.js Runtime");

    let builder = tauri::Builder::default()${sharedChain ? "\n" + indent(sharedChain, 8) : ""};
${desktopBlock}${mobileBlock}
    builder
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
`;
  await writeIfChanged(libPath, content);
}

export async function patchCargoToml(targetDir, config) {
  const cargoPath = fs.resolve(targetDir, "Cargo.toml");
  if (!fs.existsSync(cargoPath)) return;
  const { name, version, description, author, lib } = await getInfo(config);
  let content = String(await fs.readFile(cargoPath, "utf8"))
    .replace(/^name\s*=\s*".*"/m, `name = "${name}"`)
    .replace(/^version\s*=\s*".*"/m, `version = "${version}"`)
    .replace(/^description\s*=\s*".*"/m, `description = "${description}"`)
    .replace(/^authors\s*=\s*\[.*\]/m, `authors = ["${author}"]`)
    .replace(/^\[lib\]\s*\nname\s*=\s*".*"/m, `[lib]\nname = "${lib}"`);

  const tauriFeatures = config?.app?.background ? `"devtools", "tray-icon"` : `"devtools"`;
  const sharedLines = [
    `tauri = { version = "2", features = [${tauriFeatures}] }`,
    ...PLUGINS.filter((p) => !p.platforms).map(cargoLine),
  ];
  if (config?.extraCargoDependencies && typeof config.extraCargoDependencies === "object") {
    for (const [crate, spec] of Object.entries(config.extraCargoDependencies)) {
      sharedLines.push(typeof spec === "string" ? `${crate} = ${JSON.stringify(spec)}` : `${crate} = ${tomlInline(spec)}`);
    }
  }
  const mobileLines = PLUGINS.filter(
    (p) => p.platforms && (p.platforms.includes("android") || p.platforms.includes("ios")),
  ).map(cargoLine);
  const desktopLines = PLUGINS.filter((p) => p.platforms && p.platforms.includes("desktop")).map(cargoLine);

  content = replaceBlock(content, SHARED, sharedLines);
  content = replaceBlock(content, MOBILE, mobileLines);
  content = replaceBlock(content, DESKTOP, desktopLines);

  await writeIfChanged(cargoPath, content);
}

function cargoLine(p) {
  const features = p.cargoFeatures ? `, features = [${p.cargoFeatures}]` : "";
  return `${p.crate} = { version = "${p.version}"${features} }`;
}

function replaceBlock(content, marker, lines) {
  const body = lines.length ? `\n${lines.join("\n")}\n` : "\n";
  const generated = `${marker.begin}${body}${marker.end}`;
  const re = new RegExp(`${escapeRe(marker.begin)}[\\s\\S]*?${escapeRe(marker.end)}`);
  if (re.test(content)) return content.replace(re, generated);
  // Marker missing — caller is responsible for ensuring the template has the
  // marker pair. Returning unchanged is safer than guessing where to insert.
  return content;
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function tomlInline(obj) {
  const parts = Object.entries(obj).map(([k, v]) => `${k} = ${JSON.stringify(v)}`);
  return `{ ${parts.join(", ")} }`;
}
