import fs from "@vistta/fs";
import { initCall, PLUGINS } from "../plugins.config.js";
import { getInfo, resolveApplicationId, writeIfChanged } from "../utils/index.js";

const DEV = process.env.NODE_ENV === "development";

/**
 * Writes src/main.rs in full. The runtime owns this file end-to-end; there's
 * nothing to merge with the template baseline. The template's main.rs (with its
 * `vistta_app_id` placeholder) is overwritten on every build.
 */
export async function patchMainRs(targetDir, config) {
  const mainPath = fs.resolve(targetDir, "src", "main.rs");
  await fs.mkdir(fs.resolve(targetDir, "src"), { recursive: true });
  const { lib } = await getInfo(config);
  const appId = resolveApplicationId(config);
  const content = `// Generated by @vistta/js-native. Do not edit by hand.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

fn main() {
    #[cfg(target_os = "windows")]
    set_app_user_model_id();
    ${lib}::run();
}

#[cfg(target_os = "windows")]
fn set_app_user_model_id() {
    use std::os::windows::ffi::OsStrExt;
    use std::ffi::OsStr;
    let wide: Vec<u16> = OsStr::new(${JSON.stringify(appId)})
        .encode_wide()
        .chain(std::iter::once(0))
        .collect();
    unsafe {
        let _ = windows::Win32::UI::Shell::SetCurrentProcessExplicitAppUserModelID(
            windows::core::PCWSTR(wide.as_ptr())
        );
    }
}
`;
  await writeIfChanged(mainPath, content);
}

/**
 * Writes src/lib.rs in full. Plugins are partitioned by platform and chained
 * onto a shared Tauri builder. The chain is the single source of truth in
 * plugins.config.js; this function renders it for the current config. Always
 * regenerated; the template baseline is overwritten on every build.
 */
export async function patchLibRs(targetDir, config) {
  const libPath = fs.resolve(targetDir, "src", "lib.rs");
  await fs.mkdir(fs.resolve(targetDir, "src"), { recursive: true });

  const sharedPlugins = PLUGINS.filter((p) => !p.platforms);
  const desktopOnly = PLUGINS.filter((p) => p.platforms && p.platforms.includes("desktop") && !sharedPlugins.includes(p));
  const mobileOnly = PLUGINS.filter(
    (p) => p.platforms && (p.platforms.includes("android") || p.platforms.includes("ios")) && !sharedPlugins.includes(p),
  );

  const indent = (s, n) => s.replace(/^/gm, " ".repeat(n));
  const sharedChain = sharedPlugins.map((p) => `.plugin(${initCall(p)})`).join("\n");
  const desktopChain = desktopOnly.map((p) => `.plugin(${initCall(p)})`).join("\n");
  const mobileChain = mobileOnly.map((p) => `.plugin(${initCall(p)})`).join("\n");

  // Background mode is desktop-only: tray icon + hide-on-close. The block
  // is gated on `cfg(not(any(target_os = "android", target_os = "ios")))` so
  // mobile targets never see it. Requires the `tray-icon` Cargo feature,
  // which patchCargoToml adds when `app.background` is set.
  //
  // The tray menu is dynamic: JS publishes quick-actions via the
  // `set-shortcuts` Tauri event (see plugins/shortcuts.js), and a listener
  // rebuilds the menu from the payload. Menu clicks for action ids emit a
  // `launch-action` event back to the webview so the JS `onLaunchAction`
  // handler receives `{ id, payload }`. The built-in `Show/Hide` and `Quit`
  // items are always present.
  const background = !!config?.app?.background;
  const trayWindow = config?.app?.visible === false ? "ide" : "main";
  const desktopChainWithBackground = background
    ? `${desktopChain ? desktopChain + "\n" : ""}        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                let _ = window.hide();
                api.prevent_close();
            }
            if window.label() == "${trayWindow}" {
                sync_tray_window(window.app_handle());
            }
        })
        .setup(|app| {
            use tauri::tray::TrayIconBuilder;
            use tauri::menu::{Menu, MenuItem, PredefinedMenuItem};
            use tauri::{Emitter, Listener, Manager};
            use std::sync::Mutex;

            // id→payload table so the menu-event handler can recover the
            // payload for a dynamic action id.
            app.manage(Mutex::new(Vec::<(String, String)>::new()));

            let show_i = MenuItem::with_id(app, "show", "Show", true, None::<&str>)?;
            app.manage(show_i.clone());
            let quit_i = MenuItem::with_id(app, "quit", "Quit", true, None::<&str>)?;
            let menu = Menu::with_items(app, &[&show_i, &quit_i])?;

            let _tray = TrayIconBuilder::with_id("main")
                .icon(app.default_window_icon().unwrap().clone())
                .menu(&menu)
                .on_menu_event(|app, event| {
                    match event.id.as_ref() {
                        "quit" => { app.exit(0); }
                        "show" => {
                            if let Some(window) = app.get_webview_window("${trayWindow}") {
                                let result = window.is_visible().and_then(|visible| {
                                    if visible {
                                        window.hide()
                                    } else {
                                        window.show()?;
                                        window.unminimize()?;
                                        window.set_focus()
                                    }
                                });
                                if let Err(error) = result {
                                    log::error!("Could not toggle tray window: {error}");
                                }
                                sync_tray_window(app);
                            } else if let Err(error) = app.emit("launch-action", serde_json::json!({ "id": "show" })) {
                                log::error!("Could not open tray window: {error}");
                            }
                        }
                        id => {
                            let payload = app
                                .try_state::<Mutex<Vec<(String, String)>>>()
                                .and_then(|state| {
                                    let table = state.lock().ok()?;
                                    table.iter().find(|(aid, _)| aid == id).map(|(_, p)| p.clone())
                                })
                                .unwrap_or_default();
                            let _ = app.emit("launch-action", serde_json::json!({
                                "id": id,
                                "payload": payload,
                            }));
                            ${config?.app?.visible === false ? "" : `if let Some(window) = app.get_webview_window("${trayWindow}") {
                                let _ = window.show();
                                let _ = window.set_focus();
                            }`}
                        }
                    }
                })
                .build(app)?;

            // Rebuild the tray menu when JS publishes a new shortcut list.
            let handle = app.handle().clone();
            app.listen("set-shortcuts", move |event| {
                let Some(tray) = handle.tray_by_id("main") else { return };
                let payload = event.payload();
                let entries: Vec<ShortcutEntry> = match serde_json::from_str(payload) {
                    Ok(v) => v, Err(_) => return,
                };
                if let Some(state) = handle.try_state::<Mutex<Vec<(String, String)>>>() {
                    if let Ok(mut table) = state.lock() {
                        table.clear();
                        table.extend(entries.iter().map(|e| (e.id.clone(), e.payload.clone())));
                    }
                }
                let show_i = handle.state::<MenuItem<tauri::Wry>>();
                let quit_i = match MenuItem::with_id(&handle, "quit", "Quit", true, None::<&str>) {
                    Ok(i) => i, Err(_) => return,
                };
                let menu = match Menu::new(&handle) {
                    Ok(m) => m, Err(_) => return,
                };
                let _ = menu.append(show_i.inner());
                if !entries.is_empty() {
                    if let Ok(sep) = PredefinedMenuItem::separator(&handle) {
                        let _ = menu.append(&sep);
                    }
                    for e in &entries {
                        if let Ok(i) = MenuItem::with_id(&handle, &e.id, &e.label, true, None::<&str>) {
                            let _ = menu.append(&i);
                        }
                    }
                    if let Ok(sep) = PredefinedMenuItem::separator(&handle) {
                        let _ = menu.append(&sep);
                    }
                }
                let _ = menu.append(&quit_i);
                let _ = tray.set_menu(Some(menu));
                sync_tray_window(&handle);
            });

            sync_tray_window(app.handle());
            Ok(())
        })`
    : desktopChain;

  const desktopBlock = desktopChainWithBackground
    ? `
    #[cfg(not(any(target_os = "android", target_os = "ios")))]
    let builder = builder
${indent(desktopChainWithBackground, 8)};
`
    : "";

  const mobileBlock = mobileChain
    ? `
    #[cfg(any(target_os = "android", target_os = "ios"))]
    let builder = builder
${indent(mobileChain, 8)};
`
    : "";

  const singleInstance = !config?.app?.multipleInstances;
  const managerUse = background || singleInstance
    ? '    #[cfg(not(any(target_os = "android", target_os = "ios")))]\n    use tauri::Manager;\n'
    : "";

  // Unless `app.multipleInstances` is set, a second launch surfaces the
  // existing window and exits instead of starting another process. The
  // plugin must be registered before any other.
  const singleInstanceBlock = singleInstance
    ? `
    #[cfg(not(any(target_os = "android", target_os = "ios")))]
    let builder = builder.plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
        if let Some(window) = app.get_webview_window("${trayWindow}") {
            let _ = window.show();
            let _ = window.unminimize();
            let _ = window.set_focus();
        }
    }));
`
    : "";

  const content = `// Generated by @vistta/js-native. Do not edit by hand.
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
${managerUse}    env_logger::init();
    log::info!("Starting Vistta.js Runtime");

    let builder = tauri::Builder::default();
${singleInstanceBlock}${sharedChain ? `\n    let builder = builder\n${indent(sharedChain, 8)};\n` : ""}${desktopBlock}${mobileBlock}
    builder
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
${
  background
    ? `
#[cfg(not(any(target_os = "android", target_os = "ios")))]
fn sync_tray_window(app: &tauri::AppHandle) {
    use tauri::Manager;
    let visible = match app.get_webview_window("${trayWindow}") {
        Some(window) => match window.is_visible() {
            Ok(visible) => visible,
            Err(error) => {
                log::error!("Could not read tray window visibility: {error}");
                return;
            }
        },
        None => false,
    };
    if let Some(item) = app.try_state::<tauri::menu::MenuItem<tauri::Wry>>() {
        if let Err(error) = item.set_text(if visible { "Hide" } else { "Show" }) {
            log::error!("Could not update tray window action: {error}");
        }
    }
}

#[cfg(not(any(target_os = "android", target_os = "ios")))]
#[derive(serde::Deserialize)]
struct ShortcutEntry {
    id: String,
    label: String,
    #[serde(default)]
    icon: Option<String>,
    #[serde(default)]
    payload: String,
}
`
    : ""
}`;
  await writeIfChanged(libPath, content);
}

/**
 * Writes Cargo.toml in full. The runtime owns this file end-to-end: package
 * metadata, [lib] block, build deps, shared [dependencies], and the
 * per-target [dependencies] for mobile and desktop. Plugin crate entries
 * come from plugins.config.js; consumer additions come from
 * config.extraCargoDependencies. The template baseline (with its marker
 * blocks) is overwritten on every build.
 */
export async function patchCargoToml(targetDir, config) {
  const cargoPath = fs.resolve(targetDir, "Cargo.toml");
  if (!fs.existsSync(cargoPath)) return;
  const { name, version, description, author, lib } = await getInfo(config);
  // getInfo() returns a mode-stable crate name (no dev suffix) so
  // Cargo's incremental build cache isn't invalidated when switching
  // between dev and release. The dev/release binary separation is
  // handled by Cargo's own target/debug/ vs target/release/ split.

  const background = !!config?.app?.background;
  // The `devtools` Cargo feature gates whether the webview inspector can be
  // opened at all (on WebView2 it toggles `AreDevToolsEnabled`). It must only
  // be enabled in development builds so release builds cannot activate the
  // inspector. `tray-icon` is desktop-only and needed whenever background mode
  // is on, regardless of dev/release.
  const tauriFeatures = [...(DEV ? ["devtools"] : []), ...(background ? ["tray-icon"] : [])].map((f) => `"${f}"`).join(", ");
  const sharedDeps = [
    `serde = { version = "1", features = ["derive"] }`,
    `serde_json = "1"`,
    `log = "0.4"`,
    `env_logger = "0.11"`,
    `tauri = { version = "2", features = [${tauriFeatures}] }`,
    ...PLUGINS.filter((p) => !p.platforms).map(cargoLine),
  ];
  if (config?.extraCargoDependencies && typeof config.extraCargoDependencies === "object") {
    for (const [crate, spec] of Object.entries(config.extraCargoDependencies)) {
      sharedDeps.push(typeof spec === "string" ? `${crate} = ${JSON.stringify(spec)}` : `${crate} = ${tomlInline(spec)}`);
    }
  }
  const mobileDeps = PLUGINS.filter(
    (p) => p.platforms && (p.platforms.includes("android") || p.platforms.includes("ios")),
  ).map(cargoLine);
  const desktopDeps = [
    ...(config?.app?.multipleInstances ? [] : [`tauri-plugin-single-instance = "2"`]),
    ...PLUGINS.filter((p) => p.platforms && p.platforms.includes("desktop")).map(cargoLine),
  ];

  const content =
    [
      `[package]`,
      `name = "${name}"`,
      `version = "${version}"`,
      `description = "${description}"`,
      `authors = ["${author}"]`,
      `edition = "2021"`,
      ``,
      `[lib]`,
      `name = "${lib}"`,
      `crate-type = ["staticlib", "cdylib", "rlib"]`,
      ``,
      `[build-dependencies]`,
      `tauri-build = { version = "2", features = [] }`,
      ``,
      `[dependencies]`,
      ...sharedDeps,
      ``,
      `[target.'cfg(target_os = "windows")'.dependencies]`,
      `windows = { version = "0.58", features = ["Win32_UI_Shell"] }`,
      ``,
      `[target.'cfg(any(target_os = "android", target_os = "ios"))'.dependencies]`,
      ...mobileDeps,
      ``,
      `[target.'cfg(not(any(target_os = "android", target_os = "ios")))'.dependencies]`,
      ...desktopDeps,
    ]
      .filter((line, i, arr) => !(line === "" && arr[i - 1] === ""))
      .join("\n") + "\n";

  await writeIfChanged(cargoPath, content);
}

function cargoLine(p) {
  // The runtime's own plugin crate is wired in as a path dependency so it
  // compiles from source inside this package. crates.io plugins use the
  // normal version spec. The path in plugins.config.js (relative to this
  // package) points at `rust/plugin/`; resolve it to an absolute path so the
  // generated Cargo.toml (which lives in the consumer's buildDir) can find
  // it regardless of where buildDir is.
  if (p.path) {
    const absPath = fs.resolve(import.meta.dirname, "..", p.path);
    return `${p.crate} = { path = ${JSON.stringify(absPath)} }`;
  }
  const features = p.cargoFeatures ? `, features = [${p.cargoFeatures}]` : "";
  return `${p.crate} = { version = "${p.version}"${features} }`;
}

function tomlInline(obj) {
  const parts = Object.entries(obj).map(([k, v]) => `${k} = ${JSON.stringify(v)}`);
  return `{ ${parts.join(", ")} }`;
}
